_DESTROY_VERBS = ("delete", "terminate", "destroy", "purge", "remove", "disable")


@lru_cache(maxsize=1)
def _services() -> dict:
    return json.loads(_DATA.read_text(encoding="utf-8"))["services"]


@lru_cache(maxsize=1)
def action_levels() -> dict[str, dict[str, str]]:
    """{service: {action_lowercase: access level}}."""
    return {svc: {a: v[0] for a, v in data["actions"].items()} for svc, data in _services().items()}


def action_resource_types(service: str) -> dict[str, list[str]]:
    """{action_lowercase: [resource type names it can target]} -- empty means account-level."""
    return {a: v[1] for a, v in _services().get(service, {}).get("actions", {}).items()}


@lru_cache(maxsize=None)
def arn_patterns(service: str) -> dict[str, tuple[str, ...]]:
    """{resource type: ARN glob patterns}, AWS's `${Var}` placeholders made `*`."""
    import re

    resources = _services().get(service, {}).get("resources", {})
    return {
        rtype: tuple(re.sub(r"\$\{[^}]*\}", "*", f) for f in formats)
        for rtype, formats in resources.items()
    }


def capability_of_action(action: str) -> Capability:
    """One concrete action, e.g. "s3:DeleteObject". Never raises."""
    key = action.strip().lower()
    if key in OVERRIDES:
        return OVERRIDES[key]
    service, _, name = key.partition(":")
    level = action_levels().get(service, {}).get(name)
    if level is None:
        return Capability.from_token(key)
    if level == "W" and name.startswith(_DESTROY_VERBS):
        return Capability.DESTROY
    return LEVEL_CAPABILITY[level]


def capabilities_of_pattern(pattern: str) -> frozenset[Capability]:
    """
    What a policy's action pattern confers: "*" and "svc:*" are ADMIN; any other
    wildcard is the union over the AWS actions it matches (falling back to the
    verb heuristics, then UNKNOWN, when it matches none).
    """
    key = pattern.strip().lower()
    if key == "*" or (key.endswith(":*") and key.count(":") == 1):
        return frozenset({Capability.ADMIN})
    if "*" not in key and "?" not in key:
        return frozenset({capability_of_action(key)})
    service, _, name_pattern = key.partition(":")
    names = action_levels().get(service, {})
    matched = [n for n in names if fnmatch.fnmatchcase(n, name_pattern)]
    if not matched:
        return frozenset({Capability.from_token(key.replace("*", "").replace("?", ""))})
    return frozenset(capability_of_action(f"{service}:{n}") for n in matched)


def actions_matching(patterns, service: str) -> list[str]:
    """Concrete actions of one service matched by any of the patterns (for NotAction)."""
    names = action_levels().get(service, {})
    out = []
    for name in names:
        full = f"{service}:{name}"
        if any(fnmatch.fnmatchcase(full, p.strip().lower()) for p in patterns):
            out.append(full)
    return out
