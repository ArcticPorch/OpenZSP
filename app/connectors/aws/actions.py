"""
AWS IAM actions -> capabilities: an explicit table, as CLAUDE.md asks a real
connector to carry, instead of leaning on verb heuristics.

The base is AWS's own classification. `data/action_levels.json` is generated by
`tools/build_aws_action_levels.py` from the machine-readable Service Reference
(455 services, ~22,000 actions at generation time) and maps every action to its
IAM access level:

    List, Read  -> READ
    Write       -> WRITE   (Delete*/Terminate*/... -> DESTROY, see below)
    Permissions management -> MANAGE_PERMISSION   (AWS hands this one over free)
    Tagging     -> WRITE

Access level answers "what kind of API call is this", not "how much harm does
holding it confer", so a short list of overrides follows, each because the
level understates the harm. AWS files all of these under plain Write:

* **IMPERSONATE** -- `sts:AssumeRole*`, `iam:PassRole`, federation: holding it
  makes you someone else.
* **MANAGE_IDENTITY** -- minting or resetting credentials for other principals.
* **MANAGE_SECURITY_CONTROL** -- stopping the audit trail and the detectors
  that would notice everything else.
* **DEPLOY** -- shipping code or infrastructure.
* **DESTROY** -- Write actions whose verb deletes or terminates.
* **READ** for `kms:Decrypt` and friends, which AWS classes as Write but which
  *read* protected data (and are privileged on a key store, like any secret).

Policy action patterns (`s3:Get*`, `iam:*`, `*`) are expanded against the table.
A whole-service or global wildcard is ADMIN: it is every action, including the
ones that change who can do what. An action AWS does not list falls back to
`Capability.from_token`, and if that cannot place it, UNKNOWN -- retained and
counted against coverage, never defaulted to READ.
"""

